const L9 = "ABCDEFGHJ", L19 = "ABCDEFGHJKLMNOPQRST";
// every 3-3 … 5-5 point in all four corners of a 19×19 board
function cornerPoints() {
  const out = [];
  for (const a of [3, 4, 5]) for (const b of [3, 4, 5]) {
    const lo = [a - 1, b - 1], hi = [19 - a, 19 - b];
    for (const [x, y] of [[lo[0], lo[1]], [hi[0], lo[1]], [lo[0], hi[1]], [hi[0], hi[1]]]) out.push(L19[x] + (y + 1));
  }
  return [...new Set(out)];
}
